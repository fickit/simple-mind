import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import { copyFile, mkdir } from "node:fs/promises";
import path from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the GitHub repository of this plugin
*/
`;

const prod = process.argv[2] === "production";
const testPluginDir = path.join("test-vault", ".obsidian", "plugins", "simple-mind");
const external = [
  "obsidian",
  "electron",
  "@codemirror/autocomplete",
  "@codemirror/collab",
  "@codemirror/commands",
  "@codemirror/language",
  "@codemirror/lint",
  "@codemirror/search",
  "@codemirror/state",
  "@codemirror/view",
  "@lezer/common",
  "@lezer/highlight",
  "@lezer/lr",
  ...builtinModules,
];

/**
 * Copies one build's own outputs into the test vault when that build succeeds.
 *
 * Each context only touches the files it writes; copying all three from both
 * builds races on a cold checkout, where the CSS build can run before main.js
 * exists.
 *
 * @param {string[]} files Outputs owned by the build.
 */
const copyToTestVault = (files) => ({
  name: `copy-${files.join("-")}-to-test-vault`,
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length > 0) return;
      await mkdir(testPluginDir, { recursive: true });
      await Promise.all(files.map((file) => copyFile(file, path.join(testPluginDir, file))));
    });
  },
});

const jsContext = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external,
  format: "cjs",
  target: "es2021",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  plugins: [copyToTestVault(["main.js", "manifest.json"])],
});

const cssContext = await esbuild.context({
  entryPoints: ["src/styles/index.css"],
  bundle: true,
  logLevel: "info",
  outfile: "styles.css",
  minify: prod,
  plugins: [copyToTestVault(["styles.css"])],
});

if (prod) {
  await Promise.all([jsContext.rebuild(), cssContext.rebuild()]);
  await Promise.all([jsContext.dispose(), cssContext.dispose()]);
} else {
  await Promise.all([jsContext.watch(), cssContext.watch()]);
}
