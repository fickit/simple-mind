import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import { copyFile, mkdir } from "node:fs/promises";
import path from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the GitHub repository of this plugin
*/
`;

const prod = process.argv[2] === "production";
const testPluginDir = path.join("test-vault", ".obsidian", "plugins", "simple-mind");
const external = [
  "obsidian",
  "electron",
  "@codemirror/autocomplete",
  "@codemirror/collab",
  "@codemirror/commands",
  "@codemirror/language",
  "@codemirror/lint",
  "@codemirror/search",
  "@codemirror/state",
  "@codemirror/view",
  "@lezer/common",
  "@lezer/highlight",
  "@lezer/lr",
  ...builtinModules,
];

const copyToTestVaultPlugin = {
  name: "copy-to-test-vault",
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length > 0) return;
      await mkdir(testPluginDir, { recursive: true });
      await Promise.all(
        ["main.js", "manifest.json", "styles.css"].map((file) =>
          copyFile(file, path.join(testPluginDir, file)),
        ),
      );
    });
  },
};

const jsContext = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external,
  format: "cjs",
  target: "es2021",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  plugins: [copyToTestVaultPlugin],
});

const cssContext = await esbuild.context({
  entryPoints: ["src/styles/index.css"],
  bundle: true,
  logLevel: "info",
  outfile: "styles.css",
  minify: prod,
  plugins: [copyToTestVaultPlugin],
});

if (prod) {
  await Promise.all([jsContext.rebuild(), cssContext.rebuild()]);
  await Promise.all([jsContext.dispose(), cssContext.dispose()]);
} else {
  await Promise.all([jsContext.watch(), cssContext.watch()]);
}
